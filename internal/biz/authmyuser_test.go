package biz

import "testing"

// MaskMobile 对应 PHP 的 `substr_replace($mobile, '****', 3, 6)`。
//
// ⚠️⚠️ 下面的期望值是**真实 PHP 跑出来的**（用 php.exe 直接调用 substr_replace），
// **不是我手算的** —— 我第一版手算成 "138****000"（10 位），
// 实际 PHP 是 "138****00"（9 位）。
//
// 教训：跨语言函数语义（尤其是 substr_replace 这种带 offset/length 的）
// **必须实跑对拍**，手算极易出错。
//
// PHP 实测输出：
//
//	''            -> ''            ( 0 -> 0)
//	'1'           -> '1****'       ( 1 -> 5)
//	'12'          -> '12****'      ( 2 -> 6)
//	'123'         -> '123****'     ( 3 -> 7)
//	'1234'        -> '123****'     ( 4 -> 7)
//	'123456789'   -> '123****'     ( 9 -> 7)
//	'1234567890'  -> '123****0'    (10 -> 8)
//	'13800138000' -> '138****00'   (11 -> 9)   <- 少了 2 位，不是等长
//	'13912345678' -> '139****78'   (11 -> 9)
//	'18600001111' -> '186****11'   (11 -> 9)
func TestMaskMobile(t *testing.T) {
	cases := []struct{ in, want string }{
		{"", ""},                   // 外层 !empty -> ''
		{"1", "1****"},             // offset 被截断到 1
		{"12", "12****"},           // offset 被截断到 2
		{"123", "123****"},         // offset == 长度 -> 直接追加
		{"1234", "123****"},        // n <= 9 -> 无尾部
		{"123456789", "123****"},   // n=9 -> substr($s,9) 是空串
		{"1234567890", "123****0"}, // n=10 -> 保留第 9 位起的 "0"
		{"13800138000", "138****00"},
		{"13912345678", "139****78"},
		{"18600001111", "186****11"},
	}
	for _, c := range cases {
		if got := MaskMobile(c.in); got != c.want {
			t.Errorf("MaskMobile(%q) = %q, 真实 PHP 是 %q", c.in, got, c.want)
		}
	}
}

// 反向断言：确保实现没有被写成"中间 6 位打码但保留全部尾部"
// （那会得到 138****8000，长度 11）。真实 PHP 结果是 138****00（长度 9）。
func TestMaskMobile_MatchesRealPHP(t *testing.T) {
	in := "13800138000"
	got := MaskMobile(in)

	if got == "138****8000" {
		t.Fatal("实现采用了直觉写法（138****8000）—— 与 PHP substr_replace 不一致")
	}
	if got != "138****00" {
		t.Fatalf("MaskMobile(%q) = %q, 真实 PHP 是 138****00", in, got)
	}
	// 原串 11 位 -> 结果 9 位（少 2 位，不是等长）
	if len(got) != len(in)-2 {
		t.Fatalf("MaskMobile(%q) 长度 = %d, 期望 %d", in, len(got), len(in)-2)
	}
}
